 await waitFor(()=>expect((screen.getByLabelText("Decisão médica de hoje") as HTMLTextAreaElement).value).toBe("Decisão sintética explícita."));
 fireEvent.click(await screen.findByRole("button",{name:"Revisar para evolução"}));
 fireEvent.change(screen.getByLabelText("Anotação para evolução"),{target:{value:"Anotação sintética aceita, sem atualizar alergias."}});
 fireEvent.click(screen.getByRole("button",{name:"Registrar na evolução"}));
 await screen.findByText(/Anotação registrada na evolução/);
 await waitFor(()=>expect(a!.eventos().filter(e=>e.tipo==="AnotacaoEvolucao")).toHaveLength(1));
